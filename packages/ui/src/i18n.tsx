interface I18nContextValue {
  locale: UiLocale;
  /** 查内置＋app 合并字典；缺 key 回传 key 本身（可见的失败，非静默错语言）。 */
  t: (key: string) => string;
  /**
   * 计数文案：n 为 1 且字典有 `<key>.one` 时用单数形，否则用 `<key>`；`{n}` 已代入。
   * 只有英文本典写 `.one`（繁中不分单复数）。其他占位符仍由调用端代入。
   */
  tn: (key: string, n: number) => string;
}

/** 一组翻译函数：宿主组件经 useI18n 取得，非 React 的辅助函数（摘要、相对时间）以参数接收。 */
export type Translator = Pick<I18nContextValue, "t" | "tn">;

/** 依合并后的字典建出 t 与 tn——Provider、Provider 外的默认值与 translatorFor 共用同一套规则。 */
function lookups(dict: Dict): Translator {
  const t = (key: string) => dict[key] ?? key;
  const tn = (key: string, n: number) =>
    ((n === 1 ? dict[`${key}.one`] : undefined) ?? t(key)).replace("{n}", String(n));
  return { t, tn };
}

/** 不经 React 取得某语言的翻译函数（内置字典＋可选的 app 字典，同 key 时 app 覆盖内置）。 */
export function translatorFor(locale: UiLocale, messages?: Partial<Record<UiLocale, Dict>>): Translator {
  return lookups({ ...MESSAGES[locale], ...(messages?.[locale] ?? {}) });
}

/** 计数文案：数字占位符之后、隔零到两个单字、接以 s 结尾的复数名词。 */
const COUNT_MESSAGE = /\{(n|m|count)\}\s+(?:[A-Za-z-]+\s+){0,2}[A-Za-z]+s\b/;

/**
 * 两语言字典的一致性检查（fix-english-status-labels-and-plurals D4），三个 workspace 的字典测试共用：
 * 两语言键集合相等（`.one` 除外）、`.one` 只在英文且有基础键、英文计数文案用 `{n}` 并有 `.one`、
 * 对应的繁中也用 `{n}`（tn 只代入 `{n}`）。回传每个问题一行，空数组表示通过。
 */
export function dictionaryProblems(dicts: Record<UiLocale, Dict>): string[] {
  const zh = dicts["zh-CN"];
  const en = dicts.en;
  const isOne = (key: string) => key.endsWith(".one");
  const problems: string[] = [];
  for (const key of Object.keys(zh).sort()) {
    if (isOne(key)) problems.push(`.one outside en: zh-CN ${key}`);
    else if (!(key in en)) problems.push(`key only in zh-CN: ${key}`);
  }
  for (const key of Object.keys(en).sort()) {
    if (!isOne(key) && !(key in zh)) problems.push(`key only in en: ${key}`);
  }
  for (const key of Object.keys(en).sort()) {
    if (isOne(key) && !(key.slice(0, -".one".length) in en)) problems.push(`.one without a base key: ${key}`);
  }
  for (const key of Object.keys(en).sort()) {
    const match = isOne(key) ? null : COUNT_MESSAGE.exec(en[key]);
    if (!match) continue;
    if (match[1] !== "n") problems.push(`count message must use {n}: ${key}`);
    else if (!(`${key}.one` in en)) problems.push(`count message without .one: ${key}`);
    else if (key in zh && !zh[key].includes("{n}")) problems.push(`zh-CN count message must use {n} too: ${key}`);
  }
  return problems;
}

const I18nContext = createContext<I18nContextValue>({
  locale: "zh-CN",
  ...lookups(MESSAGES["zh-CN"]),
});

export interface I18nProviderProps {
  locale: UiLocale;
  /** app 层附加字典，与内置字典合并（同 key 时 app 覆盖内置）。 */
  messages?: Partial<Record<UiLocale, Dict>>;
  children: ReactNode;
}

export function I18nProvider({ locale, messages, children }: I18nProviderProps) {
  const value = useMemo<I18nContextValue>(() => {
    return { locale, ...translatorFor(locale, messages) };
  }, [locale, messages]);
  return <I18nContext.Provider value={value}>{children}</I18nContext.Provider>;
}

/** 取得 t(key)、tn(key, n) 与当前 locale；Provider 外缺省 zh-CN（既有宿主不包也不炸）。 */
export function useI18n(): I18nContextValue {
  return useContext(I18nContext);
}
